import unittest
from 校验.src.domain.timeseries_denoiser import denoise_timeline_rows


class TestTimeseriesDenoiser(unittest.TestCase):
    def test_empty_and_minimal_rows(self):
        self.assertEqual(denoise_timeline_rows([]), [])
        single = [("10-12 06:00", "平半", "0.85", "1.02", "初盘")]
        self.assertEqual(denoise_timeline_rows(single), single)
        pair = [
            ("10-12 06:00", "平半", "0.85", "1.02", "即"),
            ("10-12 05:00", "平半", "0.85", "1.02", "初盘"),
        ]
        # 初即盘两行即使同盘同水也必须保留（锚点守恒）
        res = denoise_timeline_rows(pair)
        self.assertEqual(len(res), 2)
        self.assertEqual(res[0][0], "10-12 06:00")
        self.assertEqual(res[-1][0], "10-12 05:00")

    def test_adjacent_duplicates_deduplication(self):
        # 连续相同盘口和水位
        rows = [
            ("10-12 06:03", "平半", "0.85", "1.02", "即"),
            ("10-12 06:00", "平半", "0.85", "1.02", "即"),  # 冗余
            ("10-12 05:55", "平半", "0.85", "1.02", "即"),  # 冗余
            ("10-12 05:00", "半球", "0.90", "0.95", "初盘"),
        ]
        res = denoise_timeline_rows(rows)
        # 应该只保留首行即时、盘口跳变/初盘行
        self.assertEqual(len(res), 2)
        self.assertEqual(res[0][0], "10-12 06:03")
        self.assertEqual(res[1][0], "10-12 05:00")
        self.assertEqual(res[1][1], "半球")

    def test_handicap_shift_always_preserved(self):
        # 盘口档位跳变行绝对不可剔除
        rows = [
            ("10-12 06:00", "平半", "0.85", "1.02", "即"),
            ("10-12 05:30", "平手", "0.75", "1.15", "即"),  # 档位变化
            ("10-12 05:00", "半球", "0.90", "0.95", "初盘"),
        ]
        res = denoise_timeline_rows(rows)
        self.assertEqual(len(res), 3)

    def test_ping_pong_oscillation_debounce(self):
        # 模拟用户所提真实场景：10分钟内 2.45 与 2.63 反复横跳
        rows = [
            ("10-12 06:03", "2.45", "3.70", "2.60", "94.07%", "0.93/0.95/0.95", "即"),
            ("10-12 05:58", "2.63", "3.75", "2.40", "94.02%", "1.00/0.96/0.87", "即"),
            ("10-12 05:56", "2.45", "3.70", "2.60", "94.07%", "0.93/0.95/0.95", "即"),
            ("10-12 05:50", "2.63", "3.75", "2.40", "94.02%", "1.00/0.96/0.87", "即"),
            ("10-12 05:45", "2.45", "3.70", "2.60", "94.07%", "0.93/0.95/0.95", "即"),
            ("10-12 05:40", "2.63", "3.75", "2.40", "94.02%", "1.00/0.96/0.87", "即"),
            ("10-12 05:30", "2.63", "3.75", "2.40", "94.02%", "1.00/0.96/0.87", "即"),
            ("10-12 01:00", "2.35", "3.75", "2.70", "94.11%", "0.89/0.96/0.98", "初盘"),
        ]
        res = denoise_timeline_rows(rows)
        # 横跳应该被大幅压缩，保留最新行、横跳代表极值点、初盘
        self.assertLess(len(res), len(rows))
        self.assertEqual(res[0][0], "10-12 06:03")  # 首行保留
        self.assertEqual(res[-1][0], "10-12 01:00")  # 末行保留

